  function foldSection(markup, className, summaryText) {
    const opening = `<section class="panel ${className}">`;
    const start = markup.indexOf(opening);
    if (start < 0) return markup;
    const bodyStart = start + opening.length;
    const end = markup.indexOf("</section>", bodyStart);
    if (end < 0) return markup;
    const body = markup.slice(bodyStart, end);
    const folded = `<details class="panel disclosure"><summary>${summaryText}<span>OPTIONAL</span></summary><div class="disclosure-content">${body}</div></details>`;
    return markup.slice(0, start) + folded + markup.slice(end + "</section>".length);
  }

